// Pull the blog's Atom feed into src/data/postsData.js.
// Run after publishing a post:  npm run posts
// Kept out of `npm run build` so deploys never depend on the network.
import fs from 'node:fs/promises';
import path from 'node:path';

const FEED = 'https://rupesh4604.github.io/feed.xml';
const OUT = path.resolve('src/data/postsData.js');

const decode = (s = '') =>
  s
    .replace(/^<!\[CDATA\[|\]\]>$/g, '')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;|&apos;/g, "'")
    .trim();

const tag = (xml, name) => {
  const m = xml.match(new RegExp(`<${name}[^>]*>([\\s\\S]*?)</${name}>`));
  return m ? decode(m[1]) : '';
};

const text = (html) => html.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();

const res = await fetch(FEED);
if (!res.ok) throw new Error(`Feed request failed: ${res.status}`);
const xml = await res.text();

const posts = [...xml.matchAll(/<entry>([\s\S]*?)<\/entry>/g)].map(([, e]) => {
  const url = (e.match(/<link[^>]*href="([^"]+)"/) || [])[1]?.replace(/([^:])\/\//g, '$1/') ?? '';
  const words = text(tag(e, 'content')).split(' ').filter(Boolean).length;
  return {
    title: tag(e, 'title'),
    url,
    date: tag(e, 'published').slice(0, 10),
    summary: text(tag(e, 'summary')),
    tags: [...e.matchAll(/<category term="([^"]+)"/g)].map((m) => m[1]),
    readMin: Math.max(1, Math.round(words / 220)),
  };
});

posts.sort((a, b) => b.date.localeCompare(a.date));

const body = `// Generated by scripts/fetch-posts.mjs from ${FEED}. Do not edit by hand; run \`npm run posts\`.
export const posts = ${JSON.stringify(posts, null, 2)};
`;
await fs.writeFile(OUT, body, 'utf8');
console.log(`wrote ${posts.length} posts to ${path.relative(process.cwd(), OUT)}`);
